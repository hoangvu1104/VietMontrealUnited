-- MySQL 8+ / MariaDB 10.4+. Import into an empty database using utf8mb4.
CREATE TABLE players (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 full_name VARCHAR(120) NOT NULL,
 jersey_number VARCHAR(20) NOT NULL,
 jersey_key VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_bin GENERATED ALWAYS AS (LOWER(TRIM(jersey_number))) STORED,
 CONSTRAINT players_jersey_nonempty CHECK (CHAR_LENGTH(TRIM(jersey_number)) > 0),
 UNIQUE KEY players_jersey_unique (jersey_key),
 birth_year SMALLINT UNSIGNED NULL,
 photo_path VARCHAR(190) NULL,
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('ADMIN','PLAYER') NOT NULL,
 player_id INT UNSIGNED NULL UNIQUE,
 is_active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE matches (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 match_date DATE NOT NULL, match_time TIME NOT NULL,
 opponent_name VARCHAR(120) NOT NULL, opponent_logo VARCHAR(190) NULL,
 location VARCHAR(190) NOT NULL,
 home_away ENUM('Home','Away') NOT NULL DEFAULT 'Home',
 our_score SMALLINT UNSIGNED NULL, opponent_score SMALLINT UNSIGNED NULL,
 status ENUM('Upcoming','Completed','Cancelled','Postponed') NOT NULL DEFAULT 'Upcoming',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 INDEX idx_match_schedule(status,match_date,match_time),
 CONSTRAINT completed_score CHECK(status <> 'Completed' OR (our_score IS NOT NULL AND opponent_score IS NOT NULL))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE match_availability (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 match_id INT UNSIGNED NOT NULL, player_id INT UNSIGNED NOT NULL,
 status ENUM('YES','NO','MAYBE','NO_RESPONSE') NOT NULL DEFAULT 'NO_RESPONSE',
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY match_player(match_id,player_id),
 FOREIGN KEY(match_id) REFERENCES matches(id) ON DELETE CASCADE,
 FOREIGN KEY(player_id) REFERENCES players(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE player_match_stats (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 match_id INT UNSIGNED NOT NULL, player_id INT UNSIGNED NOT NULL,
 goals SMALLINT UNSIGNED NOT NULL DEFAULT 0, assists SMALLINT UNSIGNED NOT NULL DEFAULT 0,
 updated_by INT UNSIGNED NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY match_player(match_id,player_id),
 FOREIGN KEY(match_id) REFERENCES matches(id) ON DELETE CASCADE,
 FOREIGN KEY(player_id) REFERENCES players(id) ON DELETE RESTRICT,
 FOREIGN KEY(updated_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT positive_stats CHECK(goals >= 0 AND assists >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE settings (
 setting_key VARCHAR(60) PRIMARY KEY, setting_value VARCHAR(190) NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
